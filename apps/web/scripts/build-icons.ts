/**
 * Vendors the icons this app uses out of Iconify's Lucide collection.
 *
 * `bun run icons` rewrites `src/components/ui/icon-data.ts`, which is
 * committed. Nothing fetches an icon at runtime: `@iconify/react` and the
 * Iconify API would both put a network request (and a CSP entry) between a
 * self-hosted instance and its own chrome, for artwork that never changes
 * between builds. `@iconify-json/lucide` is a devDependency for the same
 * reason — it is a build input, not a shipped one.
 *
 * Only the `stroke-width` is rewritten. Lucide draws at 2 on a 24 grid; this
 * interface is hairlines and thin type, and 2 reads heavy beside it, so the
 * attribute is dropped from the artwork and the `<svg>` supplies the house
 * weight instead. Everything else is Lucide's own geometry, untouched.
 *
 * To add an icon: put it in MAP, run `bun run icons`, export it from
 * `icons.tsx`. An unknown Lucide name fails here rather than rendering
 * nothing.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const here = dirname(fileURLToPath(import.meta.url));
const OUT = join(here, "..", "src", "components", "ui", "icon-data.ts");
const SOURCE = join(
  here,
  "..",
  "..",
  "..",
  "node_modules",
  "@iconify-json",
  "lucide",
  "icons.json",
);

