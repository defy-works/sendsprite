interface Collection {
  icons: Record<string, { body: string; width?: number; height?: number }>;
  aliases?: Record<string, { parent: string }>;
  width?: number;
  height?: number;
}

const collection = JSON.parse(readFileSync(SOURCE, "utf8")) as Collection;

function resolve(name: string) {
  const direct = collection.icons[name];
  if (direct) return direct;
  const alias = collection.aliases?.[name];
  const target = alias && collection.icons[alias.parent];
  if (target) return target;
  throw new Error(`lucide has no icon "${name}"`);
}

const lines: string[] = [];
for (const [house, lucide] of Object.entries(MAP)) {
  const { body, width, height } = resolve(lucide);
  // The grid has to be the one the `<svg>` declares, or the artwork is
  // cropped. Every Lucide icon is 24×24; anything else is a mistake worth
  // hearing about rather than rendering wrong.
  const w = width ?? collection.width ?? 24;
  const h = height ?? collection.height ?? 24;
  if (w !== 24 || h !== 24)
    throw new Error(
      `${lucide} is ${w}×${h}, not the 24 grid the renderer uses`,
    );
  const stripped = body.replaceAll(' stroke-width="2"', "");
  lines.push(`  /** lucide: ${lucide} */`);
  lines.push(`  ${house}: ${JSON.stringify(stripped)},`);
}

const file = `/**
 * Generated by \`bun run icons\` from @iconify-json/lucide. Do not edit.
 *
 * Each value is the inner markup of a 24×24 icon, with Lucide's
 * \`stroke-width="2"\` removed so the \`<svg>\` in \`icons.tsx\` can set the
 * house weight. See \`scripts/build-icons.ts\`.
 */
export const ICON_BODIES = {
${lines.join("\n")}
} as const;

export type IconName = keyof typeof ICON_BODIES;
`;

// Formatted here rather than left to whoever notices. `bun run format:check`
// gates CI, and a generator whose output fails it turns "add an icon" into a
// red build for a reason that has nothing to do with the icon.
const pretty = await format(file, {
  ...(await resolveConfig(OUT)),
  filepath: OUT,
});
writeFileSync(OUT, pretty, "utf8");
